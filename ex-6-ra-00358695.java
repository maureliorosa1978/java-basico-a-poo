public class Contador {

    public static void main(String[] args) {

        System.out.println("=============================");
        System.out.println("  Números de 1 a 10:");
        System.out.println("=============================");

        for (int i = 1; i <= 10; i++) {
            System.out.println("  " + i);
        }

        System.out.println("=============================");
    }
}
